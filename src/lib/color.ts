// Team colours are chosen by the player (S02), so their contrast cannot be
// fixed in tokens. Pick dark or light text at runtime by WCAG ratio.
const lum = (hex: string) => {
  const h = hex.replace("#", "");
  const c = [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16) / 255);
  const [r, g, b] = c.map((v) => (v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
export const contrast = (a: string, b: string) => {
  const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
};
export const readableOn = (bg: string) =>
  contrast("#0b0e13", bg) >= contrast("#ffffff", bg) ? "#0b0e13" : "#ffffff";
